const fs = require('fs');
const path = require('path');
const got = require('got');

const version = process.argv[2] || '2.3.0';
const definitelyTypedVersion = process.argv[3] || '1.7.7';
const outDir = path.join(__dirname, 'p5types');

async function fetchTypeFile(fileName) {
  const url = `https://unpkg.com/p5@${version}/types/${fileName}`;
  const body = await got(url, {
    timeout: { request: 20000 },
    followRedirect: true,
    retry: { limit: 2 }
  }).text();
  return { url, body };
}

async function fetchP5SoundTypeFile() {
  const url = `https://unpkg.com/@types/p5@${definitelyTypedVersion}/lib/addons/p5.sound.d.ts`;
  const rawBody = await got(url, {
    timeout: { request: 20000 },
    followRedirect: true,
    retry: { limit: 2 }
  }).text();

  // The @types file augments ../../index; retarget to our bundled ./p5 module.
  const body = rawBody.replace(/\.\.\/\.\.\/index/g, './p5');
  return { url, body };
}

function buildP5SoundGlobalShim(soundBody) {
  const interfaceMarker = 'interface p5InstanceExtensions {';
  const start = soundBody.indexOf(interfaceMarker);
  if (start < 0) {
    throw new Error('Could not find p5InstanceExtensions in p5.sound.d.ts');
  }

  const openBrace = soundBody.indexOf('{', start);
  let depth = 0;
  let end = -1;
  for (let i = openBrace; i < soundBody.length; i += 1) {
    const ch = soundBody[i];
    if (ch === '{') {
      depth += 1;
    } else if (ch === '}') {
      depth -= 1;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }

  if (end < 0) {
    throw new Error('Could not parse p5InstanceExtensions block');
  }

  const interfaceBody = soundBody.slice(openBrace + 1, end);
  const withoutComments = interfaceBody
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .trim();

  const classNames = [...soundBody.matchAll(/\bclass\s+([A-Za-z_]\w*)\b/g)].map((m) => m[1]);

  function qualifyModuleTypes(signatureText) {
    let qualified = signatureText;
    const uniqueSortedNames = [...new Set(classNames)].sort((a, b) => b.length - a.length);
    for (const className of uniqueSortedNames) {
      const re = new RegExp(`(^|[^\\w$.])(${className})(?=\\b)`, 'g');
      qualified = qualified.replace(re, '$1p5.$2');
    }
    return qualified;
  }

  const rawMembers = withoutComments
    .split(';')
    .map((member) => member.trim())
    .filter(Boolean);

  const globalDecls = [];
  for (const member of rawMembers) {
    const normalized = member.replace(/\r?\n\s*/g, ' ').replace(/\s+/g, ' ').trim();
    const normalizedQualified = qualifyModuleTypes(normalized);
    const colonIdx = normalized.indexOf(':');
    const parenIdx = normalized.indexOf('(');
    if (colonIdx < 0) {
      continue;
    }

    if (parenIdx >= 0 && parenIdx < colonIdx) {
      globalDecls.push(`  function ${normalizedQualified};`);
    } else {
      globalDecls.push(`  const ${normalizedQualified};`);
    }
  }

  return `// This file is auto-generated by update-p5-types.js.
// It provides global-mode declarations for p5.sound addon functions.

import p5 = require('./p5');

declare global {
${globalDecls.join('\n')}
}

export {};
`;
}

function extractRuntimeP5PrototypeMethods(minifiedRuntimePath) {
  if (!fs.existsSync(minifiedRuntimePath)) {
    return [];
  }

  const runtimeBody = fs.readFileSync(minifiedRuntimePath, 'utf8');
  const matches = [...runtimeBody.matchAll(/p5\.prototype\.([A-Za-z_$][\w$]*)\s*=/g)].map((m) => m[1]);
  return [...new Set(matches)].sort();
}

function buildRuntimeMatchedP5SoundGlobalShim(soundBody, runtimeMethods) {
  const interfaceMarker = 'interface p5InstanceExtensions {';
  const start = soundBody.indexOf(interfaceMarker);
  if (start < 0) {
    throw new Error('Could not find p5InstanceExtensions in p5.sound.d.ts');
  }

  const openBrace = soundBody.indexOf('{', start);
  let depth = 0;
  let end = -1;
  for (let i = openBrace; i < soundBody.length; i += 1) {
    const ch = soundBody[i];
    if (ch === '{') {
      depth += 1;
    } else if (ch === '}') {
      depth -= 1;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }

  if (end < 0) {
    throw new Error('Could not parse p5InstanceExtensions block');
  }

  const interfaceBody = soundBody.slice(openBrace + 1, end);
  const withoutComments = interfaceBody.replace(/\/\*[\s\S]*?\*\//g, '');
  const signatureByName = new Map();
  const lineRe = /^\s*([A-Za-z_$][\w$]*)\s*(\([\s\S]*?\)|:)\s*([\s\S]*?);\s*$/gm;
  for (const m of withoutComments.matchAll(lineRe)) {
    const name = m[1];
    const kind = m[2];
    const tail = m[3];
    const sig = `${name}${kind}${tail}`.replace(/\s+/g, ' ').trim();
    signatureByName.set(name, sig);
  }

  const manualByName = {
    setAudioContext: 'setAudioContext(audioContext: AudioContext): void',
    userStopAudio: 'userStopAudio(): Promise<void>'
  };

  const decls = [];
  for (const name of runtimeMethods) {
    if (name === 'loadSound') {
      decls.push(
        '  function loadSound(path: string | any[], successCallback?: (...args: any[]) => any, errorCallback?: (...args: any[]) => any, whileLoading?: (...args: any[]) => any): p5.SoundFile | Promise<p5.SoundFile>;'
      );
      continue;
    }

    const sig = signatureByName.get(name) || manualByName[name];
    if (!sig) {
      continue;
    }

    if (sig.includes('(') && sig.indexOf('(') < sig.indexOf(':')) {
      decls.push(`  function ${sig};`);
    } else {
      decls.push(`  const ${sig};`);
    }
  }

  return `// This file is auto-generated by update-p5-types.js.
// It provides global-mode declarations for p5.sound addon functions
// that exist in the bundled runtime p5.sound.min.js.

import p5 = require('./p5');

declare global {
${decls.join('\n')}
}

export {};
`;
}

async function main() {
  fs.mkdirSync(outDir, { recursive: true });

  const files = ['p5.d.ts', 'global.d.ts'];
  for (const fileName of files) {
    const { url, body } = await fetchTypeFile(fileName);
    const outPath = path.join(outDir, fileName);
    fs.writeFileSync(outPath, body, 'utf8');
    console.log(`Updated ${fileName} from ${url}`);
  }

  const sound = await fetchP5SoundTypeFile();
  fs.writeFileSync(path.join(outDir, 'p5.sound.d.ts'), sound.body, 'utf8');
  console.log(`Updated p5.sound.d.ts from ${sound.url}`);

  const runtimePath = path.join(__dirname, 'template', 'libraries', 'p5.sound.min.js');
  const runtimeMethods = extractRuntimeP5PrototypeMethods(runtimePath);
  const soundGlobalShim =
    runtimeMethods.length > 0
      ? buildRuntimeMatchedP5SoundGlobalShim(sound.body, runtimeMethods)
      : buildP5SoundGlobalShim(sound.body);
  fs.writeFileSync(path.join(outDir, 'p5.sound.global.d.ts'), soundGlobalShim, 'utf8');
  if (runtimeMethods.length > 0) {
    console.log(`Updated p5.sound.global.d.ts shim from runtime methods: ${runtimeMethods.join(', ')}`);
  } else {
    console.log('Updated p5.sound.global.d.ts shim');
  }

  console.log(
    `Done. p5 core types are synced to p5@${version} and p5.sound types to @types/p5@${definitelyTypedVersion}.`
  );
}

main().catch((err) => {
  console.error('Failed to update p5 types:', err.message || err);
  process.exit(1);
});
